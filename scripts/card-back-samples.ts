/**
 * Writes docs/card-back-samples.md: the German side of the card for a fixed list of
 * sample words, from the word bank, so the grammar rules can be reviewed by eye.
 *
 *   DATABASE_URL=... npx tsx scripts/card-back-samples.ts
 */
import { writeFileSync } from 'node:fs';
import { asc, inArray } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/postgres-js';
import postgres from 'postgres';
import * as table from '../src/lib/server/db/schema.js';
import { buildCardBack } from '../src/lib/card-back.js';
import type { Grammar, PartOfSpeech } from '../src/lib/grammar.js';
import { meaningGrammarFromSense } from '../src/lib/server/collection.js';

export const SAMPLES: [string, PartOfSpeech][] = [
	['machen', 'verb'],
	['arbeiten', 'verb'],
	['studieren', 'verb'],
	['sammeln', 'verb'],
	['fahren', 'verb'],
	['lesen', 'verb'],
	['geben', 'verb'],
	['essen', 'verb'],
	['bringen', 'verb'],
	['heißen', 'verb'],
	['sein', 'verb'],
	['können', 'verb'],
	['wissen', 'verb'],
	['ankommen', 'verb'],
	['verstehen', 'verb'],
	['übersetzen', 'verb'],
	['helfen', 'verb'],
	['warten', 'verb'],
	['freuen', 'verb'],
	['Hund', 'noun'],
	['Frau', 'noun'],
	['Kind', 'noun'],
	['Auto', 'noun'],
	['Junge', 'noun'],
	['Name', 'noun'],
	['Herz', 'noun'],
	['Mann', 'noun'],
	['See', 'noun'],
	['Bank', 'noun'],
	['Eltern', 'noun'],
	['Deutsche', 'noun'],
	['schnell', 'adjective'],
	['alt', 'adjective'],
	['gut', 'adjective'],
	['hoch', 'adjective'],
	['dunkel', 'adjective'],
	['teuer', 'adjective'],
	['lila', 'adjective'],
	['egal', 'adjective'],
	['stolz', 'adjective'],
	['gern', 'adverb'],
	['oft', 'adverb'],
	['nach', 'preposition'],
	['in', 'preposition'],
	['zu', 'preposition'],
	['wegen', 'preposition'],
	['weil', 'conjunction'],
	['und', 'conjunction'],
	['doch', 'particle']
];

const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set');
const client = postgres(url, { prepare: false });
const db = drizzle(client, { schema: table });

const words = await db
	.select()
	.from(table.dictWord)
	.where(
		inArray(
			table.dictWord.headword,
			SAMPLES.map(([h]) => h)
		)
	)
	.orderBy(asc(table.dictWord.id));
const senses = await db
	.select()
	.from(table.dictSense)
	.where(
		inArray(
			table.dictSense.dictWordId,
			words.map((w) => w.id)
		)
	)
	.orderBy(asc(table.dictSense.position));

const out: string[] = [
	'# Card back samples',
	'',
	'The German side of the card for sample words, as the grammar rules build it from the word bank. Generated by `scripts/card-back-samples.ts`; the first meaning of each entry is used for meaning-level grammar.',
	''
];
for (const [headword, pos] of SAMPLES) {
	const entries = words.filter((w) => w.headword === headword && w.pos === pos);
	if (!entries.length) {
		out.push(`## ${headword} (${pos})`, '', '_Not in the word bank._', '');
		continue;
	}
	for (const w of entries) {
		const sense = senses.find((s) => s.dictWordId === w.id);
		const back = buildCardBack(
			{ headword: w.headword, pos: w.pos, grammar: w.grammar as Grammar },
			sense
				? meaningGrammarFromSense(sense.details as Record<string, unknown>, sense.glosses, w.pos)
				: {}
		);
		out.push(`## ${back.title} (${pos})`, '');
		if (sense) out.push(`_${sense.glosses[0]}_`, '');
		if (back.labels.length) out.push(`Labels: ${back.labels.join(', ')}`, '');
		for (const l of back.lines) out.push(`- **${l.label}:** ${l.value}`);
		if (back.usage.length) out.push(`- **Usage:** ${back.usage.join(' · ')}`);
		if (back.table)
			out.push(
				`- **${back.table.caption}:** ${back.table.rows.map(([p, f]) => `${p} ${f}`).join(', ')}`
			);
		out.push('', `Recall prompt: ${back.recall.join(', ') || '(none)'}`, '');
	}
}
writeFileSync('docs/card-back-samples.md', out.join('\n'));
await client.end();
console.log('Wrote docs/card-back-samples.md');
